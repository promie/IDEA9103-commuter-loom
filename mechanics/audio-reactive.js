// audio-reactive.js  —  MECHANIC: Audio
//
// The sound of the city follows the data, and the fabric follows the
// sound. Three looping layers play together, each aimed at one frequency
// band:
//   - rumble (bass):  a low drone, like trains in tunnels
//   - hum (mid):      a warm, slowly swelling chord, the murmur of a crowd
//   - taps (treble):  scattered bright ticks, like Opal cards tapping on
// Each month, the data sets how loud each layer is. A busy month (2019)
// plays all three in full; a quiet month (April 2020) keeps only a faint
// rumble. The pitch also drops a little when the network is quiet.
//
// p5.FFT then analyses the mix every frame, and the frequency bands move
// the grains (the audio never draws its own visualiser):
//   - bass   squeezes every stream tight onto its track (compression)
//   - mids   shear neighbouring lines sideways against each other
//   - treble makes the grains shiver
// So in a quiet month the fabric barely reacts, and in a busy month every
// band is alive. In listening mode the selected line reacts most strongly.
//
// Sound is on by default. The layers start looping as soon as the artwork
// opens, but most browsers keep a page silent until the visitor first
// clicks, taps or presses a key. userStartAudio() asks p5.sound to unlock
// the sound at that first moment (any click, including the play/pause
// button), so it plays as early as the browser allows. Browsers that allow
// autoplay play it straight away. The speaker button mutes and unmutes it.
// Muting only silences the speakers: the analysis keeps running, so the
// fabric still breathes and moves with the (silent) sound.
//
// Each time a new month flips over, a short mechanical "clack" plays, like
// a split-flap departure board. It goes into the FFT too, so every flip
// makes the fabric shiver slightly.
//
// The four sounds were generated by script/generate_city_sound.py.
//
// AI acknowledgement: this class was written with the help of Claude
// (Anthropic).

// FFT settings: smoothing (0-1) and the number of frequency bins, which
// must be a power of two.
const FFT_SMOOTHING = 0.85;
const FFT_BINS = 1024;

// Each layer's volume in the quietest month and the busiest month.
// The rumble never fully disappears: the network is never completely
// still. The hum and taps fade right out when it is quiet.
const RUMBLE_QUIET_VOLUME = 0.1;
const RUMBLE_BUSY_VOLUME = 0.9;
const HUM_QUIET_VOLUME = 0;
const HUM_BUSY_VOLUME = 0.55;
const TAPS_QUIET_VOLUME = 0;
const TAPS_BUSY_VOLUME = 0.5;

// Playback rate in the quietest and busiest months. A slower rate also
// lowers the pitch, so quiet months sound heavier and duller.
const QUIET_RATE = 0.88;
const BUSY_RATE = 1.04;

// Button icons, drawn as small SVG pictures (the same SVG shapes we
// learned in week 1). "currentColor" means they use the button's text
// colour, so they follow the theme. A speaker with sound waves means the
// sound is on; a speaker with a cross means it is off or muted.
const SOUND_ON_ICON =
  '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M3 9v6h4l5 4V5L7 9H3z" fill="currentColor"/>' +
  '<path d="M15.5 8.5a5 5 0 0 1 0 7M18.5 5.5a9 9 0 0 1 0 13" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>';
const SOUND_OFF_ICON =
  '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M3 9v6h4l5 4V5L7 9H3z" fill="currentColor"/>' +
  '<path d="M16 9.5l5 5M21 9.5l-5 5" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>';

// The largest sideways shear (mids) and shiver (treble), in pixels.
const MAX_MID_SHEAR = 34;
const MAX_TREBLE_SHIVER = 11;

// How loud the month "clack" is, and the fewest frames between two clacks
// (so dragging quickly along the timeline does not become a buzz).
const FLIP_VOLUME = 0.45;
const FLIP_MIN_FRAMES = 6;

class AudioReactive {
  constructor(rumbleSound, humSound, tapsSound, flipSound) {
    this.rumbleSound = rumbleSound;
    this.humSound = humSound;
    this.tapsSound = tapsSound;
    this.flipSound = flipSound;
    this.layers = [rumbleSound, humSound, tapsSound];
    this.lastFlipFrame = -FLIP_MIN_FRAMES;

    // One FFT listens to all three layers. connect() sends each layer into
    // the FFT as well as to the speakers.
    this.fft = new p5.FFT(FFT_SMOOTHING, FFT_BINS);
    for (let layer of this.layers) {
      layer.connect(this.fft);
    }
    this.flipSound.connect(this.fft);
    this.flipSound.setVolume(FLIP_VOLUME);

    // Smoothed energy in each band, from 0 (silent) to 1 (loudest).
    this.bass = 0;
    this.mid = 0;
    this.treble = 0;

    // Overall loudness, from 0 to 1.
    this.level = 0;

    // The busyness last used to set the volumes, so we only change the
    // sound when the month actually changes.
    this.currentBusyness = -1;

    this.hasStarted = false;
    this.isMuted = false;

    // The button is placed by InterfaceOverlay.positionButtons().
    this.button = createButton("");
    this.button.id("audio-control");
    this.button.addClass("commuter-control");
    // Sound is on by default. start() runs in setup(), and the browser lets
    // it play from the visitor's first click, tap or key press.
    this.showButton(SOUND_ON_ICON, "Mute sound");
  }

  // Sets the button's icon, plus a label that screen readers read out
  // (aria-label) and a tooltip shown when a mouse rests on it (title).
  showButton(icon, label) {
    this.button.html(icon);
    this.button.attribute("aria-label", label);
    this.button.attribute("title", label);
  }

  // Starts the sound layers looping. Called once from setup().
  start(overlay) {
    if (this.hasStarted) {
      return;
    }
    // userStartAudio() unlocks the browser's sound on the visitor's first
    // click, tap or key press anywhere on the page.
    userStartAudio();
    // Respect a mute chosen before the sound started.
    if (this.isMuted) {
      outputVolume(0);
    } else {
      outputVolume(1);
    }
    // All three layers are 12 seconds long and start together, so they
    // stay in step as they loop.
    for (let layer of this.layers) {
      layer.loop();
    }
    this.hasStarted = true;
  }

  // The speaker button mutes and unmutes the sound.
  toggleMute(overlay) {
    this.isMuted = !this.isMuted;
    // outputVolume() sets the volume of everything p5.sound sends to the
    // speakers, fading over 0.2 seconds. The FFT listens to the layers
    // themselves, before this point, so it keeps working while muted.
    if (this.isMuted) {
      outputVolume(0, 0.2);
      this.showButton(SOUND_OFF_ICON, "Unmute sound");
      overlay.setStatus("Sound muted. The fabric still moves with the music.");
    } else {
      outputVolume(1, 0.2);
      this.showButton(SOUND_ON_ICON, "Mute sound");
      overlay.setStatus("Sound on.");
    }
  }

  // Called once per frame. getEnergy() returns 0-255 for a named band,
  // which we divide down to 0-1. lerp() smooths the values so the fabric
  // breathes rather than flickers. When the sound stops, everything eases
  // back to 0.
  update() {
    if (!this.rumbleSound.isPlaying()) {
      this.bass = lerp(this.bass, 0, 0.1);
      this.mid = lerp(this.mid, 0, 0.1);
      this.treble = lerp(this.treble, 0, 0.1);
      this.level = lerp(this.level, 0, 0.1);
      return;
    }

    this.fft.analyze();
    this.bass = lerp(this.bass, this.fft.getEnergy("bass") / 255, 0.2);
    this.mid = lerp(this.mid, this.fft.getEnergy("mid") / 255, 0.2);
    this.treble = lerp(this.treble, this.fft.getEnergy("treble") / 255, 0.25);

    // Overall loudness: the average of the three bands. Each band comes
    // from one layer, so this rises as more layers join in.
    this.level = (this.bass + this.mid + this.treble) / 3;
  }

  // Sets the mix from this month's data. busyness is 0 for the quietest
  // months and 1 for the busiest (from FabricBreath.getBusyness()).
  followData(busyness) {
    // Only update the sound when the change is big enough to hear.
    if (abs(busyness - this.currentBusyness) < 0.01) {
      return;
    }
    this.currentBusyness = busyness;

    // The hum and taps come in more gradually than the rumble: pow() with
    // a power above 1 keeps them quiet until the network is fairly busy.
    let rumbleVolume = lerp(RUMBLE_QUIET_VOLUME, RUMBLE_BUSY_VOLUME, busyness);
    let humVolume = lerp(HUM_QUIET_VOLUME, HUM_BUSY_VOLUME, pow(busyness, 1.5));
    let tapsVolume = lerp(TAPS_QUIET_VOLUME, TAPS_BUSY_VOLUME, pow(busyness, 2));

    // The second input fades to the new volume over 0.6 seconds, so the
    // sound swells and fades gently from month to month.
    this.rumbleSound.setVolume(rumbleVolume, 0.6);
    this.humSound.setVolume(humVolume, 0.6);
    this.tapsSound.setVolume(tapsVolume, 0.6);

    let rate = lerp(QUIET_RATE, BUSY_RATE, busyness);
    for (let layer of this.layers) {
      layer.rate(rate);
    }
  }

  // Plays the month "clack". It only plays once the browser has allowed
  // sound (getAudioContext().state is "running"), and not more often than
  // every FLIP_MIN_FRAMES frames.
  playFlip() {
    let soundAllowed = getAudioContext().state === "running";
    if (!this.hasStarted || !soundAllowed || frameCount - this.lastFlipFrame < FLIP_MIN_FRAMES) {
      return;
    }
    this.flipSound.play();
    this.lastFlipFrame = frameCount;
  }

  // 0 to 1: how loud the sound is overall. Deepens the network's breathing.
  getLevel() {
    return this.level;
  }

  // 0 to 1: how tightly every stream is squeezed. getEnergy() measures
  // loudness on a decibel-like scale, so even the faint rumble of a quiet
  // month reads about 0.5. map() stretches the range we actually hear
  // (about 0.45 to 0.8) to 0-1, so busy and quiet months squeeze the
  // fabric very differently.
  getBassSqueeze() {
    return map(this.bass, 0.45, 0.8, 0, 1, true);
  }

  // Pixels of sideways shear. The pow() curve lifts quieter mid levels so
  // they are visible next to the much stronger bass.
  getMidShear() {
    return pow(this.mid, 0.65) * MAX_MID_SHEAR;
  }

  // Pixels of random shiver, with the same kind of curve as the mids.
  getTrebleShiver() {
    return pow(this.treble, 0.55) * MAX_TREBLE_SHIVER;
  }
}
